using BillingBackend.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Oracle.EntityFrameworkCore.Infrastructure;
using System;
using System.IO;

namespace BillingBackend.Migrator
{
    class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("==================================================");
            Console.WriteLine("Starting SmartBilling Database Migrator...");
            Console.WriteLine("==================================================");

            // 1. Build Configuration
            var configuration = new ConfigurationBuilder()
                .SetBasePath(AppDomain.CurrentDomain.BaseDirectory)
                .AddJsonFile("appsettings.json", optional: true)
                // Search in project root and parent directories
                .AddJsonFile(Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "..", "..", "..", "BillingBackend", "appsettings.json"), optional: true)
                .AddJsonFile(Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "..", "..", "..", "..", "BillingBackend", "appsettings.json"), optional: true)
                .Build();

            var connectionString = configuration.GetConnectionString("DefaultConnection");
            if (string.IsNullOrEmpty(connectionString))
            {
                Console.ForegroundColor = ConsoleColor.Red;
                Console.WriteLine("Error: DefaultConnection string is missing from configuration.");
                Console.ResetColor();
                return;
            }

            Console.WriteLine($"Using Connection String: {connectionString}");

            // 2. Configure DB Context
            var optionsBuilder = new DbContextOptionsBuilder<BillingDbContext>();
            optionsBuilder.UseOracle(connectionString, b => 
                b.UseOracleSQLCompatibility(OracleSQLCompatibility.DatabaseVersion19));

            using (var context = new BillingDbContext(optionsBuilder.Options))
            {
                try
                {
                    // Attempt to create database/tables, but ignore failures due to pre-existing tables
                    try
                    {
                        Console.WriteLine("\n[1/2] Checking database and creating missing tables...");
                        context.Database.EnsureCreated();
                        Console.WriteLine("Database and tables checked successfully.");
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"[Warning] EnsureCreated skipped table generation because some tables already exist: {ex.Message}");
                    }

                    Console.WriteLine("\n[2/2] Applying latest schema alters (columns, constraints, and new tables)...");

                    // Explicitly create the new WhatsApp integration tables if they don't exist
                    ExecuteAlter(context, @"
                        CREATE TABLE ""WhatsAppAccounts"" (
                            ""Id"" NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                            ""BusinessId"" NUMBER(10) NOT NULL,
                            ""MetaBusinessId"" VARCHAR2(100),
                            ""WabaId"" VARCHAR2(100),
                            ""PhoneNumberId"" VARCHAR2(100),
                            ""DisplayPhoneNumber"" VARCHAR2(30),
                            ""AccessToken"" VARCHAR2(1000),
                            ""TokenExpiry"" TIMESTAMP,
                            ""Status"" VARCHAR2(20) NOT NULL,
                            ""ConnectedAt"" TIMESTAMP NOT NULL,
                            ""DisconnectedAt"" TIMESTAMP,
                            CONSTRAINT ""FK_WA_Business"" FOREIGN KEY (""BusinessId"") REFERENCES ""Businesses""(""Id"") ON DELETE CASCADE
                        )");

                    ExecuteAlter(context, @"
                        CREATE TABLE ""MessageLogs"" (
                            ""Id"" NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                            ""WhatsAppAccountId"" NUMBER(10) NOT NULL,
                            ""BillId"" NUMBER(10),
                            ""RecipientPhone"" VARCHAR2(20) NOT NULL,
                            ""MessageType"" VARCHAR2(20) NOT NULL,
                            ""MetaMessageId"" VARCHAR2(200),
                            ""Status"" VARCHAR2(20) NOT NULL,
                            ""SentAt"" TIMESTAMP NOT NULL,
                            ""DeliveredAt"" TIMESTAMP,
                            ""ReadAt"" TIMESTAMP,
                            ""FailedReason"" VARCHAR2(500),
                            CONSTRAINT ""FK_MsgLog_WA"" FOREIGN KEY (""WhatsAppAccountId"") REFERENCES ""WhatsAppAccounts""(""Id"") ON DELETE CASCADE,
                            CONSTRAINT ""FK_MsgLog_Bill"" FOREIGN KEY (""BillId"") REFERENCES ""Bills""(""Id"") ON DELETE SET NULL
                        )");

                    // General schema alters
                    ExecuteAlter(context, "ALTER TABLE \"StaffMembers\" DROP CONSTRAINT \"FK_Staff_Branches_BranchId\"");
                    ExecuteAlter(context, "ALTER TABLE \"StaffMembers\" DROP COLUMN \"BranchId\"");
                    ExecuteAlter(context, "ALTER TABLE \"Users\" ADD \"PasswordResetToken\" VARCHAR2(100) NULL");
                    ExecuteAlter(context, "ALTER TABLE \"Users\" ADD \"PasswordResetTokenExpiry\" TIMESTAMP NULL");
                    ExecuteAlter(context, "ALTER TABLE \"Categories\" ADD \"ParentId\" NUMBER(10) NULL");
                    ExecuteAlter(context, "ALTER TABLE \"Services\" ADD \"ImageUrl\" VARCHAR2(500) NULL");
                    ExecuteAlter(context, "ALTER TABLE \"InventoryItems\" ADD \"ImageUrl\" VARCHAR2(500) NULL");
                    ExecuteAlter(context, "ALTER TABLE \"Businesses\" ADD \"IsSuspended\" NUMBER(1) DEFAULT 0 NOT NULL");

                    // WhatsApp Cloud API Integration Migration
                    // Drop old WhatsApp tables (templates first due to FK, then settings)
                    ExecuteAlter(context, "DROP TABLE \"WhatsAppTemplates\"");
                    ExecuteAlter(context, "DROP TABLE \"WhatsAppSettings\"");

                    // Add InvoicePdfUrl column to Bills table
                    ExecuteAlter(context, "ALTER TABLE \"Bills\" ADD \"InvoicePdfUrl\" VARCHAR2(500) NULL");

                    // Add UserRefreshTokens table
                    ExecuteAlter(context, @"
                        CREATE TABLE ""UserRefreshTokens"" (
                            ""Id"" NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                            ""UserId"" NUMBER(10) NOT NULL,
                            ""Token"" VARCHAR2(500) NOT NULL,
                            ""ExpiryTime"" TIMESTAMP NOT NULL,
                            ""IsRevoked"" NUMBER(1) DEFAULT 0 NOT NULL,
                            ""CreatedAt"" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                            CONSTRAINT ""FK_RefreshToken_User"" FOREIGN KEY (""UserId"") REFERENCES ""Users""(""Id"") ON DELETE CASCADE
                        )");

                    // Add index on Token
                    ExecuteAlter(context, @"
                        CREATE UNIQUE INDEX ""IX_UserRefreshTokens_Token"" ON ""UserRefreshTokens""(""Token"")");


                    Console.ForegroundColor = ConsoleColor.Green;
                    Console.WriteLine("\nDatabase Migrator finished execution successfully!");
                    Console.ResetColor();
                }
                catch (Exception ex)
                {
                    Console.ForegroundColor = ConsoleColor.Red;
                    Console.WriteLine($"\nMigration Failed: {ex.Message}");
                    if (ex.InnerException != null)
                    {
                        Console.WriteLine($"Inner Exception: {ex.InnerException.Message}");
                    }
                    Console.ResetColor();
                }
            }
        }

        static void ExecuteAlter(BillingDbContext context, string sql)
        {
            try
            {
                context.Database.ExecuteSqlRaw(sql);
                Console.WriteLine($"[Applied] {sql}");
            }
            catch (Exception)
            {
                // Most alters fail if the column or constraint is already modified/present. This is normal.
                Console.WriteLine($"[Skipped - Already Applied] {sql}");
            }
        }
    }
}
